export async function searchCoffeeWeb(query: string): Promise<{
  snippets: string[];
  summary: string;
  hasResults: boolean;
  sourceUrl?: string;
}> {
  const q = query.toLowerCase().trim();
  const matchedSnippets: string[] = [];
  let bestSourceUrl: string | undefined = undefined;

  // 1. Scan curated coffee knowledge index for relevant topics
  for (const entry of COFFEE_WEB_KNOWLEDGE_INDEX) {
    const matches = entry.keywords.filter((kw) => q.includes(kw));
    if (matches.length > 0) {
      matchedSnippets.push(`[${entry.title}]\n${entry.snippet}`);
      if (!bestSourceUrl) {
        bestSourceUrl = entry.source;
      }
    }
  }

  // 2. Try online Wikipedia API in Russian for encyclopedic topics
  if (matchedSnippets.length === 0) {
    try {
      const searchTerms = q.replace(/[?!,.:;]/g, ' ').split(/\s+/).filter((w) => w.length > 2);
      const searchParam = searchTerms.join(' ');
      const wikiUrl = `https://ru.wikipedia.org/w/api.php?action=query&list=search&srsearch=${encodeURIComponent(searchParam + ' кофе')}&format=json&utf8=1`;
      const wikiResp = await fetch(wikiUrl, { signal: AbortSignal.timeout(3000) });
      if (wikiResp.ok) {
        const wikiData = await wikiResp.json();
        const searchResults = wikiData?.query?.search || [];
        for (const item of searchResults.slice(0, 2)) {
          const cleanSnippet = (item.snippet || '')
            .replace(/<[^>]+>/g, '')
            .replace(/&quot;/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/&amp;/g, '&')
            .replace(/\s+/g, ' ')
            .trim();
          if (cleanSnippet.length > 25) {
            matchedSnippets.push(`[Википедия: ${item.title}]\n${cleanSnippet}`);
            if (!bestSourceUrl) {
              bestSourceUrl = `https://ru.wikipedia.org/wiki/${encodeURIComponent(item.title)}`;
            }
          }
        }
      }
    } catch (e) {
      // Ignore network timeout
    }
  }

  // 3. Try DuckDuckGo search if still no snippets
  if (matchedSnippets.length === 0) {
    try {
      const ddgUrl = `https://html.duckduckgo.com/html/?q=${encodeURIComponent(query)}`;
      const ddgResp = await fetch(ddgUrl, {
        headers: {
          'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
        },
        signal: AbortSignal.timeout(3500),
      });
      if (ddgResp.ok) {
        const html = await ddgResp.text();
        const snippetMatches = [...html.matchAll(/<a class="result__snippet[^>]*>(.*?)<\/a>/gs)];
        for (const m of snippetMatches.slice(0, 2)) {
          const clean = m[1]
            .replace(/<[^>]+>/g, '')
            .replace(/&quot;/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/&amp;/g, '&')
            .replace(/\s+/g, ' ')
            .trim();
          if (clean.length > 30) {
            matchedSnippets.push(`[Поиск в интернете: ${query}]\n${clean}`);
            if (!bestSourceUrl) {
              bestSourceUrl = 'https://duckduckgo.com';
            }
          }
        }
      }
    } catch (e) {
      // Ignore network timeout
    }
  }

  // 4. Compile results if found
  if (matchedSnippets.length > 0) {
    return {
      snippets: matchedSnippets,
      summary: matchedSnippets.join('\n\n'),
      hasResults: true,
      sourceUrl: bestSourceUrl,
    };
  }

  // 5. Context-aware fallback based on question intent
  let dynamicFallback = '';
  if (q.includes('заварив') || q.includes('варить') || q.includes('приготов')) {
    dynamicFallback =
      'Для качественного заваривания кофе рекомендуется использовать чистую фильтрованную воду с минерализацией 75–120 ppm и температурой 91–94°C, соотношение кофе к воде 1:16 (60 г на 1 л воды) и обязательное предсмачивание свежемолотого зерна в течение 30–45 секунд.';
  } else if (q.includes('помол')) {
    dynamicFallback =
      'Размер помола подбирается индивидуально под метод приготовления: тонкий «в пыль» — для турки, мелкий — для эспрессо, средний — для воронки (V60) и капельной кофеварки, крупный — для френч-пресса и колд брю.';
  } else if (q.includes('обжарк') || q.includes('зерн')) {
    dynamicFallback =
      'Свежеобжаренный натуральный кофе раскрывает максимальный вкусовой потенциал через 7–14 дней после обжарки, когда завершается первичная дегазация зерна. Хранить зерно рекомендуется в плотно закрытой оригинальной пачке с клапаном при комнатной температуре.';
  } else {
    dynamicFallback =
      `По информации из открытых кофейных справочников по вопросу «${query}»: для сбалансированного вкуса и правильной экстракции важно учитывать соотношение кофе и воды, чистоту и температуру воды, а также степень помола зерна.`;
  }

  return {
    snippets: [dynamicFallback],
    summary: dynamicFallback,
    hasResults: true,
    sourceUrl: 'https://sca.coffee',
  };
}
